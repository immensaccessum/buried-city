// Generates assets/src/web/resList.js: every sprite sheet (.plist + .png) and standalone
// image under assets/res, preloaded before the menu (the native engine loads these
// synchronously on demand; the browser engine needs them in cc.loader's cache first).
// Audio is not listed - cc.audioEngine loads it lazily on first play.
// assets/res/ext/ (loose extension sprites) is included by the walk below.
var fs = require("fs");
var path = require("path");
var assets = path.join(__dirname, "..", "assets");

function walk(dir) {
    return fs.readdirSync(path.join(assets, dir)).reduce(function (out, name) {
        var rel = dir + "/" + name;
        if (fs.statSync(path.join(assets, rel)).isDirectory()) return out.concat(walk(rel));
        return /\.(png|jpg|plist)$/.test(name) ? out.concat(rel) : out;
    }, []);
}
var list = walk("res").sort();
fs.writeFileSync(path.join(assets, "src", "web", "resList.js"),
    "// Generated by tools/build-res-list.js - do not edit.\nvar WEB_PRELOAD_RESOURCES = " + JSON.stringify(list, null, 4) + ";\n");
console.log(list.length + " resources");
